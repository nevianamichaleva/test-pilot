/** Най-новият урок първи (по addedAt; при еднаква дата — редът в LESSONS, най-горният е по-нов). */
export function getAllLessons() {
  return LESSONS.map((l, index) => ({ ...l, _index: index }))
    .sort((a, b) => {
      const byDate = String(b.addedAt || "").localeCompare(String(a.addedAt || ""));
      if (byDate !== 0) return byDate;
      return a._index - b._index;
    })
    .map(({ _index, ...rest }) => rest);
}

export function getLesson(classNum, subject, slug) {
  const c = String(classNum ?? "");
  const s = String(subject ?? "");
  const g = String(slug ?? "");
  return LESSONS.find((l) => l.classNum === c && l.subject === s && l.slug === g) ?? null;
}
