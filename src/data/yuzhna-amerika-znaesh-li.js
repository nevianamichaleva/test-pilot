/** Построява решетка { "r,c": letter } и размери. */
export function buildCrosswordGrid(entries) {
  const cells = {};
  let maxR = 0;
  let maxC = 0;
  for (const w of entries) {
    for (let i = 0; i < w.answer.length; i += 1) {
      const r = w.dir === "across" ? w.row : w.row + i;
      const c = w.dir === "across" ? w.col + i : w.col;
      const key = `${r},${c}`;
      const ch = w.answer[i];
      if (cells[key] && cells[key] !== ch) {
        throw new Error(`Crossword conflict at ${key}: ${cells[key]} vs ${ch}`);
      }
      cells[key] = ch;
      if (r > maxR) maxR = r;
      if (c > maxC) maxC = c;
    }
  }
  const numberAt = {};
  for (const w of entries) {
    const key = `${w.row},${w.col}`;
    if (numberAt[key] == null || w.num < numberAt[key]) numberAt[key] = w.num;
  }
  return { cells, maxR, maxC, numberAt };
}
